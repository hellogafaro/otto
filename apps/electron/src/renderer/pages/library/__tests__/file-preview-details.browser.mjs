import { createServer } from 'vite'
import react from '@vitejs/plugin-react'
import tailwind from '@tailwindcss/vite'
import assert from 'node:assert/strict'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { resolve } from 'node:path'
import { createServer as createNetServer } from 'node:net'

const root = fileURLToPath(new URL('../../../../../../../', import.meta.url))
const fixtures = fileURLToPath(new URL('./', import.meta.url))
const out = process.env.FILE_DETAILS_PROOF_DIR || resolve(process.env.HOME || root, '.capy/work/file-preview-details-proof')
mkdirSync(out, { recursive: true })
const baselinePath = process.env.FILE_DETAILS_BASELINE_PATH
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const reservation = createNetServer()
await new Promise((resolve, reject) => reservation.once('error', reject).listen(0, '127.0.0.1', resolve))
const address = reservation.address()
assert(address && typeof address === 'object')
const port = address.port
assert(Number.isInteger(port) && port > 0 && ![5173, 19100].includes(port))
await new Promise((resolve) => reservation.close(resolve))
const server = await createServer({
  configFile: false, root: fixtures, cacheDir: resolve(out, 'vite-cache'),
  plugins: [{ name: 'file-preview-details-fixture', load(id) {
    if (baselinePath && id.split('?')[0] === resolve(root, 'apps/electron/src/renderer/pages/library/file-preview.tsx')) return readFileSync(baselinePath, 'utf8')
    if (baselinePath && id.split('?')[0] === resolve(root, 'apps/electron/src/renderer/index.css')) return readFileSync(id.split('?')[0], 'utf8') + `\n@source ${JSON.stringify(baselinePath)};\n`
  }, configureServer(instance) {
    instance.middlewares.use(async (req, res, next) => {
      if (req.url?.split('?')[0] !== '/') return next()
      res.setHeader('Content-Type', 'text/html')
      res.end(await instance.transformIndexHtml('/', '<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>Controlled actual FilePreview Details fixture</title></head><body><div id="root"></div><script type="module" src="/file-preview-details.fixture.tsx"></script></body></html>'))
    })
  } }, react(), tailwind()],
  resolve: { alias: [
    { find: '@', replacement: resolve(root, 'apps/electron/src/renderer') },
    { find: '@config', replacement: resolve(root, 'packages/shared/src/config') },
    { find: 'react', replacement: resolve(root, 'node_modules/react') },
    { find: 'react-dom', replacement: resolve(root, 'node_modules/react-dom') },
  ], dedupe: ['react', 'react-dom'] },
  server: { host: '127.0.0.1', port, strictPort: true, fs: { allow: [root, out] } },
})
let browser
try {
  await server.listen()
  assert.equal(server.httpServer.address().port, port)
  console.log('ISOLATED_PORT', port)
  browser = await chromium.launch({ headless: true, ...(process.env.CHROMIUM_EXECUTABLE ? { executablePath: process.env.CHROMIUM_EXECUTABLE } : {}) })
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
  const errors = []
  page.on('pageerror', (error) => { errors.push(error.message); console.error('PAGE_ERROR', error.message) })
  await page.goto(`http://127.0.0.1:${server.httpServer.address().port}`)
  const dialog = page.getByRole('dialog')
  const details = page.getByRole('complementary', { name: 'Details', includeHidden: true })
  const open = page.getByRole('button', { name: 'Open Details', exact: true })
  const close = page.getByRole('button', { name: 'Close Details', exact: true })
  const fileClose = page.getByRole('button', { name: 'Close', exact: true })
  await page.getByRole('heading', { name: 'Controlled file preview' }).waitFor()
  await page.waitForFunction(() => document.querySelector('.shiki') !== null)
  await page.evaluate(() => document.fonts.ready)
  const focus = async (control) => { await page.waitForFunction((label) => document.activeElement?.getAttribute('aria-label') === label, await control.getAttribute('aria-label')) }
  if (baselinePath) {
    assert.equal(await details.isVisible(), true)
    assert.equal(await open.count(), 0)
    assert.equal(await close.count(), 0)
    await page.screenshot({ path: resolve(out, 'baseline-desktop.png') })
    await page.setViewportSize({ width: 390, height: 844 })
    assert.equal(await details.isVisible(), false)
    await page.screenshot({ path: resolve(out, 'baseline-narrow.png') })
    console.log('BASELINE existing Details is desktop-only and has no pane control')
  } else {
    assert.equal(await details.isVisible(), true)
    assert.equal(await open.count(), 0)
    assert.equal(await close.count(), 1)
    assert.equal(await close.locator('xpath=ancestor::aside').count(), 1)
    assert.equal(await close.locator('svg.lucide-list').count(), 1)
    assert.equal(await fileClose.locator('svg.lucide-x').count(), 1)
    assert.equal(await page.locator('button:visible svg.lucide-list').count(), 1)
    assert.equal(await page.locator('.typeset').evaluate((node) => getComputedStyle(node).maxWidth), '555px')
    await page.screenshot({ path: resolve(out, 'desktop-open-light.png') })
    const reads = await page.evaluate(() => proof.reads.length)
    await close.click()
    await open.waitFor()
    await focus(open)
    assert.equal(await details.isVisible(), false)
    assert.equal(await open.getAttribute('aria-expanded'), 'false')
    assert.equal(await open.getAttribute('aria-controls'), await details.getAttribute('id'))
    assert.equal(await open.locator('svg.lucide-list').count(), 1)
    assert.equal(await page.getByRole('button', { name: 'Close Details' }).count(), 0)
    assert.equal(await page.locator('button:visible svg.lucide-list').count(), 1)
    assert.equal(await page.evaluate(() => proof.reads.length), reads)
    await page.screenshot({ path: resolve(out, 'desktop-closed-light.png') })
    await page.evaluate(() => proof.refresh())
    await page.waitForFunction(() => document.querySelector('[data-fixture-refresh]')?.getAttribute('data-fixture-refresh') === '1')
    assert.equal(await details.isVisible(), false)
    await page.evaluate(() => proof.navigate('text'))
    await page.getByRole('dialog', { name: 'Source fixture.ts' }).waitFor()
    await page.waitForFunction(() => document.querySelector('.shiki code')?.textContent?.includes('source_fixture'))
    assert.equal(await details.isVisible(), false)
    assert.equal(await page.locator('.typeset').evaluate((node) => getComputedStyle(node).maxWidth), 'none')
    assert(await page.locator('[data-ca-block-type="code"]').evaluate((node) => node.getBoundingClientRect().width) > 555)
    await open.click()
    await focus(close)
    assert.equal(await open.count(), 0)
    assert.equal(await close.getAttribute('aria-expanded'), 'true')
    await page.keyboard.press('Escape')
    await open.waitFor()
    await focus(open)
    assert.equal(await dialog.isVisible(), true)
    assert.equal(await page.evaluate(() => proof.closes), 0)
    console.log('PASS default open, single List control placement, explicit-close rerender/navigation persistence, focus, and separate Escape/file-close scope')

    await page.evaluate(() => proof.setAvailable(false))
    await details.waitFor({ state: 'detached' })
    assert.equal(await open.count(), 0)
    await page.evaluate(() => proof.setAvailable(true))
    await open.waitFor()
    assert.equal(await details.isVisible(), false)
    await page.evaluate(() => proof.remount())
    await close.waitFor()
    assert.equal(await details.isVisible(), true)
    await page.evaluate(() => proof.setDark(true))
    await page.waitForFunction(() => document.querySelector('.shiki.github-dark') !== null)
    await page.waitForTimeout(400)
    await page.screenshot({ path: resolve(out, 'desktop-open-dark.png') })

    await page.setViewportSize({ width: 390, height: 844 })
    const bounds = await details.evaluate((node) => {
      const preview = node.previousElementSibling.getBoundingClientRect()
      const pane = node.getBoundingClientRect()
      const dialog = node.closest('[role="dialog"]').getBoundingClientRect()
      const body = node.querySelector('[data-slot="sidecar-body"]')
      return { preview: { bottom: preview.bottom, height: preview.height }, pane: { top: pane.top, bottom: pane.bottom, right: pane.right, height: pane.height }, dialog: { bottom: dialog.bottom, right: dialog.right }, scrollable: body.scrollHeight > body.clientHeight }
    })
    assert(bounds.preview.bottom <= bounds.pane.top + 1)
    assert(bounds.pane.bottom <= bounds.dialog.bottom + 1)
    assert(bounds.pane.right <= bounds.dialog.right)
    assert(bounds.preview.height > 100 && bounds.pane.height > 100)
    assert.equal(bounds.scrollable, true)
    writeFileSync(resolve(out, 'narrow-layout.json'), JSON.stringify(bounds, null, 2))
    await page.screenshot({ path: resolve(out, 'narrow-open-dark.png') })
    await close.focus()
    for (let i = 0; i < 16; i++) {
      await page.keyboard.press('Tab')
      await page.waitForFunction(() => !!document.activeElement?.closest('[role="dialog"]'), null, { timeout: 2000 })
      assert.equal(await page.evaluate(() => !!document.activeElement?.closest('[role="dialog"]')), true)
    }
    await close.click()
    await focus(open)
    assert.equal(await details.isVisible(), false)
    for (const label of ['More actions', 'Open Details', 'Download', 'Copy link', 'Delete', 'Close']) {
      const rect = await page.getByRole('button', { name: label, exact: true }).boundingBox()
      assert(rect && rect.x >= 0 && rect.x + rect.width <= 390)
    }
    await page.screenshot({ path: resolve(out, 'narrow-closed-dark.png') })
    await page.setViewportSize({ width: 1440, height: 900 })
    assert.equal(await details.isVisible(), false)
    await page.setViewportSize({ width: 390, height: 844 })
    assert.equal(await details.isVisible(), false)
    await page.evaluate(() => proof.setDark(false))
    await page.waitForFunction(() => document.querySelector('.shiki.github-light') !== null)
    await open.click()
    await focus(close)
    await page.screenshot({ path: resolve(out, 'narrow-open-light.png') })
    assert.equal(await fileClose.isVisible(), true)
    assert.equal(await page.evaluate(() => proof.closes), 0)
    assert.deepEqual(await page.evaluate(() => proof.effects), [])
    await fileClose.click()
    await dialog.waitFor({ state: 'hidden' })
    assert.equal(await page.evaluate(() => proof.closes), 1)
    assert.deepEqual(errors, [])
    console.log('PASS metadata availability/remount defaults, narrow stacked nonoverlap/scrolling, modal keyboard focus, resize persistence, real Close X, zero download/network/business effects')

    await page.setViewportSize({ width: 1440, height: 900 })
    await page.goto(`http://127.0.0.1:${port}/?routed=1`)
    await close.waitFor()
    assert.equal(await details.isVisible(), true)
    assert.equal(await page.evaluate(() => proof.sharedOpen), false)
    assert.equal(new URL(page.url()).searchParams.get('details'), null)
    await close.click()
    await page.waitForURL((url) => url.searchParams.get('details') === 'closed')
    await focus(open)
    assert.equal(await details.isVisible(), false)
    await page.screenshot({ path: resolve(out, 'native-closed-before-reload.png') })
    await page.reload()
    await open.waitFor()
    await page.waitForFunction(() => document.querySelector('.shiki') !== null)
    assert.equal(new URL(page.url()).searchParams.get('details'), 'closed')
    assert.equal(await details.isVisible(), false)
    assert.equal(await close.count(), 0)
    assert.equal(await page.evaluate(() => proof.sharedOpen), false)
    await page.screenshot({ path: resolve(out, 'native-closed-after-reload.png') })
    await page.evaluate(() => proof.refresh())
    await page.waitForFunction(() => document.querySelector('[data-fixture-refresh]')?.getAttribute('data-fixture-refresh') === '1')
    assert.equal(await details.isVisible(), false)
    await page.evaluate(() => proof.remount())
    await open.waitFor()
    assert.equal(await details.isVisible(), false)
    await open.click()
    await page.waitForURL((url) => url.searchParams.get('details') === null)
    await focus(close)
    assert.equal(await details.isVisible(), true)
    await page.reload()
    await close.waitFor()
    assert.equal(await details.isVisible(), true)
    assert.equal(await page.evaluate(() => proof.sharedOpen), false)
    await close.focus()
    await page.keyboard.press('Escape')
    await page.waitForURL((url) => url.searchParams.get('details') === 'closed')
    await focus(open)
    assert.equal(await page.evaluate(() => proof.closes), 0)
    await page.setViewportSize({ width: 390, height: 844 })
    await page.reload()
    await open.waitFor()
    assert.equal(await details.isVisible(), false)
    await open.click()
    await page.waitForURL((url) => url.searchParams.get('details') === null)
    await focus(close)
    assert.equal(await details.isVisible(), true)
    assert.equal(await page.evaluate(() => proof.sharedOpen), false)
    assert.deepEqual(await page.evaluate(() => proof.effects), [])
    assert.deepEqual(errors, [])
    writeFileSync(resolve(out, 'native-result.json'), JSON.stringify({ closedURLPersistedOnReload: true, reopenRemovedClosedPreference: true, nativeRemountRetainedChoice: true, frameSlotStayedUnregistered: true, port }, null, 2))
    console.log('PASS actual native BrowserHistory URL details=closed, real page.reload persistence, reopen/remount, native Escape/focus, and no second Frame pane registration')
  }
} finally {
  await browser?.close()
  await server.close()
}
