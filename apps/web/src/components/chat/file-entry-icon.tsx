export function FileEntryIcon({
  pathValue,
  kind,
  className,
}: {
  pathValue: string;
  kind: "file" | "directory";
  className?: string;
}) {
  const Icon = kind === "directory" ? RiFolderLine : FILE_ICONS[resolveFileIconKind(pathValue)];

  return <Icon aria-hidden="true" className={cn("size-4 shrink-0 text-icon-muted", className)} />;
}
