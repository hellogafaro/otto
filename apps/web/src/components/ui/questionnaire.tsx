/**
 * Otto: shadcn's Questionnaire (base-mira registry) for a bot's questions, one at a time,
 * on one 16px inset like a dialog: an optional muted meta line (“1 of 3”), the 14px/500
 * question, then quiet choice rows led by their number Kbd (it fills with the foreground
 * color and a check appears at the right when picked, on an accent row), the regular `Input` for a typed
 * answer, and a bordered footer with Back / Next / Send.
 */
function Questionnaire({
  className,
  ...props
}: React.ComponentProps<typeof QuestionnairePrimitive.Root>) {
  return (
    <QuestionnairePrimitive.Root
      data-slot="questionnaire"
      className={cn("flex w-full min-w-0 flex-col gap-3 pt-4", className)}
      {...props}
    />
  );
}

