// Otto: like the dropdown's: destructive items always red; `shortcut` shows
// the item's key as a Kbd and runs it while the menu is open.
function ContextMenuItem({
  className,
  inset,
  variant = "default",
  shortcut,
  children,
  ...props
}: ContextMenuPrimitive.Item.Props & {
  inset?: boolean
  variant?: "default" | "destructive"
  shortcut?: string
}) {
  return (
    <ContextMenuPrimitive.Item
      data-slot="context-menu-item"
      data-inset={inset}
      data-variant={variant}
      data-shortcut={shortcut}
      className={cn(
        "group/context-menu-item relative flex cursor-default items-center h-7 gap-2 rounded-sm px-2 text-sm outline-hidden select-none has-[>[data-slot=context-menu-shortcut]:last-child]:pr-1 focus:bg-accent focus:text-accent-foreground data-inset:pl-8 data-[variant=destructive]:text-destructive data-[variant=destructive]:focus:bg-destructive/10 data-[variant=destructive]:focus:text-destructive dark:data-[variant=destructive]:focus:bg-destructive/20 data-disabled:pointer-events-none data-disabled:opacity-50 [&_svg]:pointer-events-none [&_svg]:shrink-0 [&_svg:not([class*='size-'])]:size-3.5 focus:*:[svg]:text-accent-foreground data-[variant=destructive]:*:[svg]:text-destructive",
        className
      )}
      {...props}
    >
      {children}
      {shortcut && (
        <Kbd data-slot="context-menu-shortcut" className="ml-auto">
          {shortcut}
        </Kbd>
      )}
    </ContextMenuPrimitive.Item>
  )
}

