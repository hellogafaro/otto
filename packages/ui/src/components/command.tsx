import { RiCheckLine, RiSearchLine } from "@remixicon/react";
import {
  Dialog,
  DialogContent,
  DialogDescription,
  DialogHeader,
  DialogTitle,
} from "@workspace/ui/components/dialog";
import { Command as CommandPrimitive } from "cmdk";
import { cn } from "cn";
import type * as React from "react";

// Otto: the menu surface (dark, translucent, blurred) at card radius (xl):
// a borderless 48px search field over a full-width divider, then 36px rows
// with md radius inside the list's 8px padding (16 − 8). Text and icons sit
// 16px in. 14px icons, foreground/10 highlight.
function Command({
  className,
  ...props
}: React.ComponentProps<typeof CommandPrimitive>) {
  return (
    <CommandPrimitive
      data-slot="command"
      className={cn(
        "flex size-full flex-col overflow-hidden rounded-xl bg-popover text-popover-foreground in-data-[slot=dialog-content]:bg-transparent",
        className,
      )}
      {...props}
    />
  );
}

function CommandDialog({
  title = "Command Palette",
  description = "Search for a command to run...",
  children,
  className,
  showCloseButton = false,
  ...props
}: Omit<React.ComponentProps<typeof Dialog>, "children"> & {
  title?: string;
  description?: string;
  className?: string;
  showCloseButton?: boolean;
  children: React.ReactNode;
}) {
  return (
    <Dialog {...props}>
      <DialogContent
        className={cn(
          "dark top-[15dvh] translate-y-0 overflow-hidden rounded-xl! bg-popover/70 p-0 shadow-md backdrop-blur-2xl backdrop-saturate-150",
          className,
        )}
        showCloseButton={showCloseButton}
      >
        {/* Otto: inside the content, so the hidden title exists only while open. */}
        <DialogHeader className="sr-only">
          <DialogTitle>{title}</DialogTitle>
          <DialogDescription>{description}</DialogDescription>
        </DialogHeader>
        {children}
      </DialogContent>
    </Dialog>
  );
}

function CommandInput({
  className,
  ...props
}: React.ComponentProps<typeof CommandPrimitive.Input>) {
  return (
    <div
      data-slot="command-input-wrapper"
      className="flex h-12 shrink-0 items-center gap-2 border-b border-foreground/10 px-4"
    >
      <RiSearchLine className="size-3.5 shrink-0 text-muted-foreground" />
      <CommandPrimitive.Input
        data-slot="command-input"
        className={cn(
          "h-full w-full bg-transparent text-sm outline-hidden placeholder:text-muted-foreground disabled:cursor-not-allowed disabled:opacity-50",
          className,
        )}
        {...props}
      />
    </div>
  );
}

